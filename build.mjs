mkdirSync('themes', { recursive: true })

for (const [mode, p] of Object.entries(palettes)) {
  const name = `Juxt ${mode === 'dark' ? 'Dark' : 'Light'}`
  const theme = {
    $schema: 'vscode://schemas/color-theme',
    name,
    type: mode,
    semanticHighlighting: true,
    colors: colors(p),
    tokenColors: tokenColors(p.syntax, p),
    semanticTokenColors: semanticTokenColors(p.syntax),
  }
  const file = `themes/juxt-${mode}-color-theme.json`
  writeFileSync(file, JSON.stringify(theme, null, 2) + '\n')
  console.log(`wrote ${file}`)
}
